import { chromium, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
const page=await context.newPage();
let passed=0;const errors=[];
const check=(label,result)=>{assert.ok(result,label);passed++;console.log('PASS '+label);};
page.on('pageerror',error=>errors.push(error.message));
try{
  await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
  const intro=page.getByRole('dialog',{name:'Welcome to TM Concepts'});
  await expect(intro).toHaveAttribute('data-phase','brand');
  check('Opening brand sequence appears',await intro.isVisible());
  check('Page is protected from accidental clicks during intro',await page.locator('.entrance-site').evaluate(el=>el.inert));
  check('Uses the supplied logo and signature',await intro.getByRole('img',{name:'TM Concepts',exact:true}).isVisible()&&await intro.getByRole('img',{name:'Toxic With Events',exact:true}).isVisible());
  await expect.poll(()=>page.locator('.entrance-signature').evaluate(el=>Number(getComputedStyle(el).opacity)),{intervals:[80]}).toBeGreaterThan(.98);
  await page.screenshot({path:'artifacts/entrance-logo-desktop.jpg',type:'jpeg',quality:85});
  await expect(intro).toHaveAttribute('data-phase','slogan');
  await expect.poll(()=>page.locator('.entrance-slogan').evaluate(el=>Number(getComputedStyle(el).opacity)),{intervals:[80]}).toBeGreaterThan(.98);
  check('Slogan follows the logo',await intro.getByText('BEFORE IT HAPPENS.',{exact:true}).isVisible());
  await page.screenshot({path:'artifacts/entrance-slogan-desktop.jpg',type:'jpeg',quality:85});
  await expect(intro).not.toBeAttached({timeout:5000});
  check('Intro automatically reveals the website',!await page.locator('.entrance-site').evaluate(el=>el.inert));
  check('Scrolling is restored',await page.evaluate(()=>getComputedStyle(document.body).overflow!=='hidden'));
  check('Focus moves to the page content',await page.locator('main').evaluate(el=>document.activeElement===el));
  await page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('link',{name:'Work',exact:true}).click();
  check('Internal navigation does not replay the intro',await page.locator('.site-entrance').count()===0);
  await page.reload({waitUntil:'domcontentloaded'});
  await expect(intro).toBeVisible();
  await intro.getByRole('button',{name:'Skip intro',exact:false}).click();
  await expect(intro).not.toBeAttached();
  check('Skip intro opens the page immediately',!await page.locator('.entrance-site').evaluate(el=>el.inert));
  await page.reload({waitUntil:'domcontentloaded'});
  await expect(intro).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(intro).not.toBeAttached();
  check('Escape skips the intro',!await page.locator('.entrance-site').evaluate(el=>el.inert));
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
  await expect(intro).toHaveAttribute('data-phase','brand');
  await expect.poll(()=>page.locator('.entrance-signature').evaluate(el=>Number(getComputedStyle(el).opacity)),{intervals:[80]}).toBeGreaterThan(.98);
  check('Mobile intro fits the viewport',await intro.evaluate(el=>el.scrollWidth<=innerWidth));
  await page.screenshot({path:'artifacts/entrance-logo-mobile.jpg',type:'jpeg',quality:85});
  await expect(intro).not.toBeAttached({timeout:5000});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.reload({waitUntil:'domcontentloaded'});
  await expect(intro).toHaveAttribute('data-phase','reduced');
  check('Reduced motion uses a static introduction',await page.locator('.entrance-logo-art').evaluate(el=>getComputedStyle(el).animationName==='none'));
  await expect(intro).not.toBeAttached({timeout:2500});
  check('Reduced-motion introduction finishes quickly',!await page.locator('.entrance-site').evaluate(el=>el.inert));
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.route('**/images/tm-logo.png',route=>route.abort());
  await page.reload({waitUntil:'domcontentloaded'});
  await expect(page.locator('.entrance-logo-fallback')).toBeVisible();
  check('Logo failure has a text fallback',await page.locator('.entrance-signature').getByText('Toxic With Events',{exact:true}).isVisible());
  await expect(intro).not.toBeAttached({timeout:6000});
  check('Logo failure cannot trap visitors in the intro',!await page.locator('.entrance-site').evaluate(el=>el.inert));
  await page.unroute('**/images/tm-logo.png');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.reload({waitUntil:'domcontentloaded'});
  await expect(intro).not.toBeAttached({timeout:3500});
  const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  const violations=audit.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}));
  check('Page stays accessible after the intro',violations.length===0);
  check('No browser errors',errors.length===0);
  await writeFile('artifacts/entrance-checks.json',JSON.stringify({passed,errors,violations},null,2));
  console.log(`${passed} entrance checks passed.`);
}catch(error){await page.screenshot({path:'artifacts/entrance-failure.jpg',type:'jpeg',quality:85});console.error(error);process.exitCode=1;}
finally{await browser.close();}

